/* eslint-disable no-console */
/**
 * Generates a D1 migration for schema changes pulled in from upstream.
 *
 *   pnpm cf:migrate:diff <name>
 *
 * Diffs the last committed prisma/schema.sqlite.prisma (git HEAD) against the
 * working-tree version and writes prisma/migrations-d1/NNNN_<name>.sql.
 * No database connection is needed.
 */
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '../..');

/**
 * @prisma/adapter-d1 stores DateTime as 'YYYY-MM-DDTHH:MM:SS.SSS+00:00'. Make DB-side
 * defaults use the same format so string comparisons in raw SQL stay consistent.
 */
export function canonicalizeDefaults(sql: string): string {
  return sql.replace(
    /DEFAULT CURRENT_TIMESTAMP/g,
    "DEFAULT (strftime('%Y-%m-%dT%H:%M:%f+00:00', 'now'))",
  );
}
const schema = path.join(root, 'prisma/schema.sqlite.prisma');
const migrationsDir = path.join(root, 'prisma/migrations-d1');
const name = (process.argv[2] || 'upstream_sync').replace(/[^\w]+/g, '_');

if (!fs.existsSync(schema)) {
  console.error('prisma/schema.sqlite.prisma missing; run `pnpm cf:schema` first.');
  process.exit(1);
}

let previous = '';
try {
  previous = execFileSync('git', ['show', 'HEAD:prisma/schema.sqlite.prisma'], {
    cwd: root,
    encoding: 'utf8',
  });
} catch {
  console.log('No committed schema.sqlite.prisma found; diffing from an empty database.');
}

const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'umami-d1-'));
const fromArgs: string[] = ['--from-empty'];

if (previous) {
  const prevPath = path.join(tmp, 'previous.prisma');
  fs.writeFileSync(prevPath, previous);
  fromArgs.splice(0, 1, '--from-schema', prevPath);
}

const sql = execFileSync(
  'pnpm',
  [
    'exec',
    'prisma',
    'migrate',
    'diff',
    '--config',
    'prisma.cloudflare.config.ts',
    ...fromArgs,
    '--to-schema',
    schema,
    '--script',
  ],
  { cwd: root, encoding: 'utf8', stdio: ['ignore', 'pipe', 'inherit'] },
);

fs.rmSync(tmp, { recursive: true, force: true });

if (!sql.trim() || /This is an empty migration/.test(sql)) {
  console.log('No schema changes detected.');
  process.exit(0);
}

fs.mkdirSync(migrationsDir, { recursive: true });

const existing = fs
  .readdirSync(migrationsDir)
  .filter(f => /^\d{4}_.*\.sql$/.test(f))
  .sort();
const next = String(existing.length + 1).padStart(4, '0');
const file = path.join(migrationsDir, `${next}_${name}.sql`);

fs.writeFileSync(
  file,
  `-- Generated by scripts/cloudflare/d1-migration-diff.ts\n${canonicalizeDefaults(sql)}`,
);
console.log(`Wrote ${path.relative(root, file)}`);
